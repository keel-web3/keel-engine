// Three.js r180's ShaderLib programs the renderer draws with (MIT, see NOTICE),
// under KEEL's names:
//
//   flat      r180 basic         (meshbasic_vert / meshbasic_frag)
//   lit       r180 standard      (meshphysical_vert / meshphysical_frag, as ShaderLib.standard uses them)
//   toon      r180 toon          (meshtoon_vert / meshtoon_frag)
//   billboard r180 sprite        (sprite_vert / sprite_frag)
//   depth     r180 depth         (depth_vert / depth_frag; shadow maps)
//   distance  r180 distanceRGBA  (distanceRGBA_vert / distanceRGBA_frag; point light shadow maps)
//   shadow    r180 shadow        (shadow_vert / shadow_frag; ShadowMaterial)
//
// The texts are r180's, byte for byte, with their `#include`s unresolved (the
// renderer resolves them from CHUNKS, as r180's WebGLProgram does). `uniforms()`
// returns a fresh r180-merged set each call, as WebGLPrograms' cloneUniforms
// of ShaderLib[id].uniforms gives each material; defaults are descriptors (see
// uniforms.ts), realized by the renderer. Texts generated from r180's sources.

import { descriptors, mergeUniforms, UNIFORM_GROUPS as L, type UniformDefault, type UniformDefaults } from "./uniforms.ts";

export interface Program {
	/** A fresh copy of the program's merged default uniforms. */
	uniforms(): UniformDefaults;
	readonly vertexShader: string;
	readonly fragmentShader: string;
}

export type ProgramName = "flat" | "lit" | "toon" | "billboard" | "depth" | "distance" | "shadow";

