// Rebuild the embedded browser module from the readable, import-free WAT.
// Run from the repository root: node packages/elevation/src/generate-nearest-raster.mjs
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const source = fileURLToPath(new URL("./nearest-raster.wat", import.meta.url));
const binary = fileURLToPath(new URL("./nearest-raster.wasm", import.meta.url));
const output = fileURLToPath(new URL("./nearest-raster-bytes.ts", import.meta.url));
execFileSync("wat2wasm", [source, "-o", binary]);
const bytes = readFileSync(binary);
const sha256 = createHash("sha256").update(bytes).digest("hex");
writeFileSync(output, `// Generated by generate-nearest-raster.mjs from nearest-raster.wat.\n// SHA-256: ${sha256}\nexport const NEAREST_RASTER_BYTES = new Uint8Array([\n${Array.from(bytes, (b, i) => `${i % 16 === 0 ? "  " : ""}${b}${i === bytes.length - 1 ? "" : ","}${i % 16 === 15 ? "\n" : " "}`).join("")}\n]);\n`);
console.log(`nearest-raster.wasm ${bytes.length} bytes ${sha256}`);
