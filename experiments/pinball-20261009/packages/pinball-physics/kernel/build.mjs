import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
const dir=fileURLToPath(new URL('.',import.meta.url));
const compiler=process.env.PINBALL_CLANG ?? '/opt/homebrew/bin/wasm32-clang';
const version=execFileSync(compiler,['--version'],{encoding:'utf8'}).split('\n')[0];
execFileSync(compiler,['-std=c17','-O2','-fno-builtin','-nostdlib','-Wl,--no-entry','-Wl,--export-all','-Wl,--initial-memory=131072','-Wl,--max-memory=131072','-Wl,--strip-all',dir+'pinball.c','-o',dir+'pinball.wasm']);
const bytes=readFileSync(dir+'pinball.wasm');const digest=createHash('sha256').update(bytes).digest('hex');
writeFileSync(dir+'../src/kernel-bytes.ts',`// Generated by kernel/build.mjs; exact independent kernel/pinball.wasm bytes.\nexport const KERNEL_SHA256 = '${digest}';\nexport const KERNEL_COMPILER = ${JSON.stringify(version)};\nexport const KERNEL_BYTES = new Uint8Array([${bytes.join(',')}]);\n`);
console.log(JSON.stringify({digest,bytes:bytes.length,compiler:version}));
